"""Generate the reference pages of the documentation site from the code.

Writes ``docs/content/reference/document-fields.md``, ``models.md``,
``expressions.md`` and ``api/*.md`` from ``Model.describe()``, the signatures
and docstrings of the public API, and by compiling the cheat-sheet expressions
with ``scixplorer.search.to_solr``. Run it after changing any of those::

    uv run python scripts/gen_docs.py          # rewrite the pages
    uv run python scripts/gen_docs.py --check  # exit 1 if any page is out of date

The output depends only on the code and the packaged data: the reference-data
cache is pointed at an empty directory and the configuration is left at its
defaults while generating.
"""


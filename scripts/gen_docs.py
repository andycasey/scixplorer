#: Signatures shown without the parameters that only exist for several tokens' sake are not needed:
#: signatures are shown without type annotations, and the types are described in the text.


def docstring(path: str, obj: Any) -> str:
    """The Markdown for an object's docstring, applying :data:`OVERRIDES`."""
    doc = inspect.getdoc(obj) or ""
    if path in OVERRIDES:
        phrase, text = OVERRIDES[path]
        if phrase not in doc:
            raise SystemExit(f"gen_docs: the docstring of {path} changed (no {phrase!r}); review OVERRIDES")
        doc = text
    return markdown(doc)


def signature(name: str, obj: Any) -> str:
    """``name(params)`` without annotations, or ``""`` if there is no signature."""
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return ""
    params: list[str] = []
    keyword_only_marked = False
    previous = None
    for parameter in sig.parameters.values():
        if parameter.name in ("self", "cls"):
            continue
        kind = parameter.kind
        if previous == inspect.Parameter.POSITIONAL_ONLY and kind != previous:
            params.append("/")
        if kind == inspect.Parameter.VAR_POSITIONAL:
            keyword_only_marked = True
        if kind == inspect.Parameter.KEYWORD_ONLY and not keyword_only_marked:
            params.append("*")
            keyword_only_marked = True
        text = {inspect.Parameter.VAR_POSITIONAL: "*", inspect.Parameter.VAR_KEYWORD: "**"}.get(kind, "") + parameter.name
        if parameter.default is not inspect.Parameter.empty:
            text += "=" + _default(parameter.default)
        params.append(text)
        previous = kind
    return f"{name}({', '.join(params)})"


def _default(value: Any) -> str:
    """A default value as source text; functions by their dotted name (never a memory address)."""
    if callable(value) and hasattr(value, "__qualname__"):
        return f"{value.__module__}.{value.__qualname__}"
    return repr(value)


def entry(path: str, obj: Any, *, label: str | None = None, level: int = 3, note: str = "") -> str:
    """One API entry: heading with the dotted path, signature, docstring."""
    name = path.rsplit(".", 1)[-1]
    kind = ""
    if isinstance(obj, property):
        kind = "property"
    elif isinstance(obj, classmethod):
        kind = "class method"
        obj = obj.__func__
    elif isinstance(obj, staticmethod):
        obj = obj.__func__
    elif inspect.isclass(obj):
        kind = "class"
    heading = "#" * level + f" {label or path}"
    parts = [heading] + ([note] if note else [])
    if kind == "property":
        parts.append(f"*property* `{name}`")
        target: Any = obj.fget
    else:
        target = obj
        call = signature(name, obj)
        if call:
            parts.append(f"```python\n{('async def ' if inspect.iscoroutinefunction(obj) else '')}{call}\n```")
        if kind:
            parts.append(f"*{kind}*")
    text = docstring(path, target)
    if text:
        parts.append(text)
    return "\n\n".join(parts)


def members(cls: type, *, names: Iterable[str] | None = None, inherited: bool = False) -> list[tuple[str, Any]]:
    """Public methods and properties of ``cls`` with docstrings, in definition order."""
    found: dict[str, Any] = {}
    sources = list(reversed(cls.__mro__[:-1])) if inherited else [cls]
    for source in sources:
        for name, value in vars(source).items():
            if name.startswith("_") and name not in ("__iter__", "__len__", "__contains__", "__aiter__"):
                continue
            if isinstance(value, (property, classmethod, staticmethod)) or inspect.isfunction(value):
                found[name] = value
    wanted = list(names) if names is not None else list(found)
    return [(name, found[name]) for name in wanted if name in found and (inspect.getdoc(found[name]) or isinstance(found[name], property))]


def class_entry(cls: type, *, names: Iterable[str] | None = None, inherited: bool = False, skip: Iterable[str] = ()) -> str:
    path = f"{cls.__module__}.{cls.__qualname__}"
    alias = public(path)
    note = f"Written `{alias}` after `from scixplorer import *`." if alias != path else ""
    parts = [entry(path, cls, label=f"{path}", level=2, note=note)]
    for name, value in members(cls, names=names, inherited=inherited):
        if name in skip:
            continue
        parts.append(entry(f"{path}.{name}", value))
    return "\n\n".join(parts)


def function_entry(module: Any, name: str, *, level: int = 2) -> str:
    obj = getattr(module, name)
    path = f"{module.__name__}.{name}"
    alias = public(path)
    note = f"Written `{alias}` after `from scixplorer import *`." if alias != path else ""
    return entry(path, obj, level=level, note=note)


def constant_entry(module: Any, name: str, doc: str) -> str:
    value = getattr(module, name)
    shown = repr(value)
    if len(shown) > 300:
        shown = shown[:297] + "..."
    return f"### {module.__name__}.{name}\n\n```python\n{name} = {shown}\n```\n\n{doc}"


# Field tables.


def _flags(info: Any, deferred: frozenset[str] = frozenset()) -> str:
    notes = []
    if not info.stored:
        notes.append("search-only")
    if info.name in deferred:
        notes.append("deferred")
    if not info.indexed:
        notes.append("not searchable")
    return ", ".join(notes)


def field_table(model: type[Model], names: Iterable[str] | None = None, *, solr: bool = False) -> str:
    infos = {info.name: info for info in model.describe()}
    deferred: frozenset[str] = getattr(model, "_deferred", frozenset())
    header = "| Field | " + ("Solr name | " if solr else "") + "Type | Match | Notes | Description |"
    rule = "|---|" + ("---|" if solr else "") + "---|---|---|---|"
    rows = [header, rule]
    for name in names if names is not None else infos:
        info = infos[name]
        solr_cell = (code(info.solr_name) if info.solr_name != info.name else "") if solr else None
        cells = [code(info.name)] + ([solr_cell] if solr else []) + [
            code(info.type),
            info.match_kind,
            _flags(info, deferred),
            cell(_inline(info.doc)),
        ]
        rows.append("| " + " | ".join(c or "" for c in cells) + " |")
    return "\n".join(rows)


def relation_table(model: type[Model]) -> str:
    rows = ["| Relation | Related model | Through | Description |", "|---|---|---|---|"]
    for name, relation in model._relations.items():
        related = relation.related_model
        rows.append(
            f"| {code(name)} | {code(public(f'{related.__module__}.{related.__qualname__}'))} | "
            f"{code(relation.key)} → {code(relation.related_key)} | {cell(_inline(relation.__doc__ or ''))} |"
        )
    return "\n".join(rows)



# Pages.


def page(title: str, weight: int, description: str, body: str) -> str:
    """A generated page: front matter, the generated-file marker, then ``body``."""
    front = f"---\ntitle: {_yaml(title)}\nweight: {weight}\ndescription: {_yaml(description)}\n---\n"
    return f"{front}\n{MARKER}\n\n{body.strip()}\n"


def _yaml(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cell(text: str) -> str:
    """Text for a Markdown table cell: pipes escaped, newlines joined."""
    return " ".join(text.split()).replace("|", "\\|")


def code(text: str) -> str:
    """An inline code span for a table cell, with pipes escaped."""
    fence = "``" if "`" in text else "`"
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{text.replace('|', chr(92) + '|')}{pad}{fence}"


# Public names, for writing references as users write them after ``from scixplorer import *`` (``Document``).


def _public_names() -> dict[str, str]:
    """Map ``module.qualname`` of every public object to the way users write it."""
    names: dict[str, str] = {}
    for name in scix.__all__:
        obj = getattr(scix, name)
        if inspect.ismodule(obj):
            names[obj.__name__] = name
            for member in getattr(obj, "__all__", ()):
                value = getattr(obj, member)
                key = f"{getattr(value, '__module__', obj.__name__)}.{getattr(value, '__qualname__', member)}"
                names.setdefault(key, f"{name}.{member}")
                names.setdefault(f"{obj.__name__}.{member}", f"{name}.{member}")
        elif hasattr(obj, "__qualname__"):
            names[f"{obj.__module__}.{obj.__qualname__}"] = name
        else:
            names[f"scixplorer._config.{name}"] = name
    return names


PUBLIC = _public_names()
_EXPORTED = re.compile(r"\bscixplorer\.(?=(?:" + "|".join(scix.__all__) + r")\b)")


def public(path: str) -> str:
    """How users write the object at dotted ``path``: ``Document``, ``search.to_solr``, ``scixplorer.expr.Order``."""
    if path in PUBLIC:
        return PUBLIC[path]
    for prefix in sorted(PUBLIC, key=len, reverse=True):
        if path.startswith(prefix + "."):
            return PUBLIC[prefix] + path[len(prefix) :]
    return path


def qualify(text: str) -> str:
    """Code as users write it after ``from scixplorer import *``: ``scixplorer.Document`` becomes ``Document``.

    Imports of exported names in examples become ``from scixplorer import *``.
    """
    if re.search(r"^\s*(from\s+scixplorer\s+import|import\s+scixplorer\b)", text, flags=re.M):
        text = re.sub(r"^\s*(from\s+scixplorer\s+import|import\s+scixplorer\b).*\n?", "", text, flags=re.M)
        text = "from scixplorer import *\n" + text
    return _EXPORTED.sub("", text)


# Docstrings: reST to Markdown.

_ROLE = re.compile(r":(?:class|meth|func|attr|data|mod|exc|obj):`(~?)([^`]+)`")
_LITERAL = re.compile(r"``(.+?)``", re.S)
_FIELD = re.compile(r"^:(param|returns?|raises?)\s*([^:]*):\s*(.*)$")


def _role(match: re.Match[str]) -> str:
    short, target = match.group(1) == "~", match.group(2)
    if target.startswith("scixplorer."):
        return f"`{public(target)}`"
    return f"`{qualify(target.rsplit('.', 1)[-1] if short else target)}`"


def _inline(text: str) -> str:
    """Convert inline reST in one paragraph to Markdown, escaping HTML outside code."""
    parts = re.split(r"(``.+?``|:\w+:`[^`]+`)", text, flags=re.S)
    out = []
    for part in parts:
        if part.startswith("``") and part.endswith("``"):
            out.append("`" + qualify(part[2:-2]) + "`")
        elif _ROLE.fullmatch(part):
            out.append(_ROLE.sub(_role, part))
        else:
            out.append(part.replace("<", "&lt;").replace(">", "&gt;"))
    return "".join(out)


def markdown(doc: str | None) -> str:
    """A docstring as Markdown: paragraphs, literal blocks as code, ``:param:`` fields as a list."""
    if not doc:
        return ""
    lines = inspect.cleandoc(doc).splitlines()
    blocks: list[str] = []
    params: list[tuple[str, str]] = []
    returns: list[str] = []
    paragraph: list[str] = []
    i = 0

    def flush() -> None:
        if paragraph:
            blocks.append(_inline(" ".join(line.strip() for line in paragraph)))
            paragraph.clear()

    while i < len(lines):
        line = lines[i]
        field = _FIELD.match(line.strip()) if not line.startswith(" ") else None
        if field is not None:
            flush()
            text = [field.group(3)]
            i += 1
            while i < len(lines) and lines[i].startswith(" ") and lines[i].strip():
                text.append(lines[i].strip())
                i += 1
            body = _inline(" ".join(text))
            if field.group(1) == "param":
                params.append((field.group(2).strip(), body))
            else:
                returns.append(body)
            continue
        if not line.strip():
            flush()
            i += 1
            continue
        if line.rstrip().endswith("::") or line.lstrip().startswith(">>>"):
            if line.lstrip().startswith(">>>"):
                flush()
                block = []
                while i < len(lines) and lines[i].strip():
                    block.append(lines[i])
                    i += 1
                blocks.append("```python\n" + qualify(textwrap.dedent("\n".join(block))) + "\n```")
                continue
            head = line.rstrip()[:-2].rstrip()
            if head:
                paragraph.append(head + ":")
            flush()
            i += 1
            block: list[str] = []
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                block.append(lines[i])
                i += 1
            blocks.append("```python\n" + qualify(textwrap.dedent("\n".join(block)).strip("\n")) + "\n```")
            continue
        paragraph.append(line)
        i += 1
    flush()
    if params:
        blocks.append("**Parameters**\n\n" + "\n".join(f"- `{name}`: {text}" for name, text in params))
    if returns:
        blocks.append("**Returns** " + " ".join(returns))
    return "\n\n".join(blocks)



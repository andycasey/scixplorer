def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated page is out of date")
    args = parser.parse_args(argv)
    stale = []
    for relative, build in PAGES.items():
        path = REFERENCE / relative
        text = build()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(relative)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check and stale:
        print("Out of date (run uv run python scripts/gen_docs.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    if not args.check:
        print(f"Wrote {len(stale)} of {len(PAGES)} pages" if stale else "All pages up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

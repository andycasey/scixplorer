def client_api() -> str:
    from scixplorer import _config, client

    fields = dataclasses.fields(_config.Config)
    missing = [f.name for f in fields if f.name not in CONFIG_FIELDS]
    if missing or set(CONFIG_FIELDS) - {f.name for f in fields}:
        raise SystemExit(f"gen_docs: CONFIG_FIELDS is out of date ({missing})")
    rows = ["| Setting | Default | Meaning |", "|---|---|---|"]
    for f in fields:
        rows.append(f"| {code(f.name)} | {code(repr(f.default))} | {CONFIG_FIELDS[f.name]} |")
    config = class_entry(_config.Config, names=["resolve_token", "resolve_collections"])
    parts = [
        "## scixplorer.config\n\nThe `Config` instance every client uses unless it is given its own. Written "
        "`config`; change its attributes to change the settings.\n\n" + "\n".join(rows),
        config,
        class_entry(client.Client, names=["send", "asend", "close", "aclose"]),
        "### scixplorer.client.Client.rate_limits\n\n*attribute* `rate_limits`\n\nA `dict` from service "
        "(such as `\"search/query\"`) to the `RateLimit` SciX last reported for it.",
        function_entry(client, "get_default_client"),
        function_entry(client, "set_default_client"),
        class_entry(client.Request, names=["is_idempotent"]),
        class_entry(client.Response),
        class_entry(client.RateLimit),
    ]
    return page("Client and Config", 3, "The HTTP client, its configuration, and the request and response values.", "\n\n".join(parts))


def exceptions_api() -> str:
    from scixplorer import exceptions

    classes = [
        value
        for value in vars(exceptions).values()
        if inspect.isclass(value) and issubclass(value, BaseException) and value.__module__ == exceptions.__name__
    ]
    parts = []
    for cls in classes:
        bases = ", ".join(f"`{public(f'{b.__module__}.{b.__qualname__}')}`" if b.__module__.startswith("scixplorer") else f"`{b.__name__}`" for b in cls.__bases__)
        parts.append(class_entry(cls) + f"\n\nDerives from {bases}.")
    return page("Exceptions", 4, "Every exception and warning scixplorer raises.", "\n\n".join(parts))



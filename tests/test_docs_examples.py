"""Run every Python example in the documentation site and the README.

Each fenced ``python`` block in ``docs/content/**/*.md`` (except generated
pages) and in ``README.md`` is executed. The blocks of one page run in order,
in one shared namespace, against an offline stand-in for the SciX API
(``docs_fakes.DocsAPI``) with no API token in the environment and the
reference-data cache in a temporary directory holding small vocabulary
extracts. Nothing touches the network.

An HTML comment on the line before a block changes how it is run:

- ``<!-- docs-test: skip -->``: not executed (pending features, or code that
  cannot run offline).
- ``<!-- docs-test: raises NAME -->``: must raise an exception whose class is named NAME.
- ``<!-- docs-test: warns NAME[, NAME] -->``: may emit warnings of those
  categories; any other block fails if it emits a warning.

A line ``# -> TEXT`` directly after an expression statement (several may
follow one statement) is checked: TEXT must occur in the ``repr`` or ``str``
of the expression's value, or in what the statement printed.

User-facing pages import only the names they use: the first Python block of
each page starts with a line such as ``from scixplorer import Document, search``,
with the names sorted. Between them, a page's ``from scixplorer import`` lines
name every public name its blocks use and nothing the blocks do not use, and
no page writes ``from scixplorer import *`` or ``import scixplorer``. The
developer pages are exempt.
"""

from __future__ import annotations

import ast
import contextlib
import dataclasses
import functools
import io
import re
import traceback
import warnings
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import pytest
from docs_fakes import PLANETARY_FEATURES_CSV, UAT_JSON, DocsAPI, refresh_transport

import scixplorer
import scixplorer.client
import scixplorer.data

ROOT = Path(__file__).resolve().parents[1]
CONTENT = ROOT / "docs" / "content"
README = ROOT / "README.md"
DEVELOPER = CONTENT / "development"

#: Generated pages carry this marker (see scripts/gen_docs.py); their blocks are not run.
GENERATED_MARKER = "<!-- Generated by scripts/gen_docs.py"

_IMPORT_LINE = re.compile(r"^from scixplorer import [A-Za-z_]\w*(, [A-Za-z_]\w*)*$")
_PLAIN_IMPORT = re.compile(r"^\s*import\s+scixplorer\b")
_FROM_PACKAGE = re.compile(r"^\s*from\s+scixplorer\s+import\s+(?P<names>.+?)\s*(#.*)?$")
_FENCE = re.compile(r"^(?P<indent>\s*)```(?P<lang>[A-Za-z0-9_+-]*)")
_DIRECTIVE = re.compile(r"^\s*<!--\s*docs-test:\s*(?P<kind>skip|raises|warns)\b\s*(?P<arg>[^>]*?)\s*-->\s*$")
_EXPECT = re.compile(r"^\s*# -> (?P<text>.*?)\s*$")
_TOKEN_VARS = ("SCIX_API_TOKEN", "ADS_API_TOKEN", "ADS_DEV_KEY")


@dataclass(frozen=True)
class Block:
    """One fenced Python block of a page."""

    page: Path
    line: int
    source: str
    directive: str | None = None
    argument: str = ""

    @property
    def label(self) -> str:
        return f"{_page_id(self.page)}:{self.line}"


def blocks(page: Path) -> list[Block]:
    """The ``python`` blocks of a page, with the directive on the line before each."""
    lines = page.read_text(encoding="utf-8").splitlines()
    found: list[Block] = []
    i = 0
    while i < len(lines):
        fence = _FENCE.match(lines[i])
        if fence is None:
            i += 1
            continue
        indent, lang = fence.group("indent"), fence.group("lang")
        start = i
        i += 1
        body: list[str] = []
        while i < len(lines) and not re.match(rf"^{re.escape(indent)}```\s*$", lines[i]):
            body.append(lines[i][len(indent) :] if lines[i].startswith(indent) else lines[i].lstrip())
            i += 1
        i += 1
        if lang != "python":
            continue
        previous = next((lines[j] for j in range(start - 1, -1, -1) if lines[j].strip()), "")
        directive = _DIRECTIVE.match(previous)
        found.append(
            Block(
                page,
                start + 1,
                "\n".join(body) + "\n",
                directive.group("kind") if directive else None,
                directive.group("arg") if directive else "",
            )
        )
    return found


def pages() -> list[Path]:
    """Every page whose examples are run: hand-written site pages and the README."""
    found = [
        path
        for path in sorted(CONTENT.rglob("*.md"))
        if GENERATED_MARKER not in path.read_text(encoding="utf-8")
    ]
    return [*found, README]


def _page_id(page: Path) -> str:
    return str(page.relative_to(ROOT)) if page.is_relative_to(ROOT) else str(page)


# Running blocks.


class ExampleFailure(AssertionError):
    """An example block did not do what the page says."""


def _statements(source: str) -> Iterator[tuple[ast.stmt, list[str]]]:
    """Each top-level statement with the ``# ->`` expectations on the lines right after it."""
    tree = ast.parse(source)
    lines = source.splitlines()
    for statement in tree.body:
        expected = []
        line = statement.end_lineno or statement.lineno
        while line < len(lines):
            match = _EXPECT.match(lines[line])
            if match is None:
                break
            expected.append(match.group("text"))
            line += 1
        if expected and not isinstance(statement, ast.Expr):
            raise ExampleFailure(f"line {statement.lineno}: '# ->' must follow an expression, not a {type(statement).__name__}")
        yield statement, expected


def _run_statement(statement: ast.stmt, namespace: dict[str, Any], filename: str) -> tuple[Any, str]:
    """Execute one statement; return its value (for an expression) and what it printed."""
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        if isinstance(statement, ast.Expr):
            code = compile(ast.Expression(statement.value), filename, "eval")
            value = eval(code, namespace)
        else:
            module = ast.Module(body=[statement], type_ignores=[])
            exec(compile(module, filename, "exec"), namespace)
            value = None
    return value, out.getvalue()


def run_block(block: Block, namespace: dict[str, Any], *, show: bool = False) -> int:
    """Run one block in ``namespace``; return the number of ``# ->`` checks made.

    Raises :class:`ExampleFailure` describing what went wrong. With ``show``,
    print each expression's value (for writing the pages).
    """
    allowed = {name.strip() for name in block.argument.split(",")} if block.directive == "warns" else set()
    expected_error = block.argument.strip() if block.directive == "raises" else None
    checks = 0
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        try:
            for statement, expectations in _statements(block.source):
                value, printed = _run_statement(statement, namespace, block.label)
                if show and isinstance(statement, ast.Expr):
                    print(f"[{block.label} line {statement.lineno}] {printed}{value!r}")
                for text in expectations:
                    checks += 1
                    if text not in repr(value) and text not in str(value) and text not in printed:
                        raise ExampleFailure(
                            f"line {statement.lineno}: expected {text!r} in the value, got\n"
                            f"  repr: {value!r}\n  str: {value}\n  printed: {printed!r}"
                        )
        except ExampleFailure:
            raise
        except Exception as exc:
            if expected_error is not None and type(exc).__name__ == expected_error:
                expected_error = None
            else:
                detail = "".join(traceback.format_exception(type(exc), exc, exc.__traceback__)[-3:])
                raise ExampleFailure(f"raised {type(exc).__name__}: {exc}\n{detail}") from exc
        if expected_error is not None:
            raise ExampleFailure(f"was expected to raise {expected_error}, but did not")
    unexpected = [w for w in caught if w.category.__name__ not in allowed]
    if unexpected:
        raise ExampleFailure(
            "emitted warnings (mark the block with <!-- docs-test: warns NAME --> if intended): "
            + "; ".join(f"{w.category.__name__}: {w.message}" for w in unexpected)
        )
    return checks


@contextlib.contextmanager
def offline_environment(tmp: Path, monkeypatch: pytest.MonkeyPatch) -> Iterator[DocsAPI]:
    """The environment every page runs in; yields the offline API serving it."""
    cache = tmp / "cache"
    home = tmp / "home"
    cache.mkdir()
    home.mkdir()
    for name in _TOKEN_VARS:
        monkeypatch.delenv(name, raising=False)
    monkeypatch.delenv("XDG_CACHE_HOME", raising=False)
    monkeypatch.setenv("SCIX_CACHE_DIR", str(cache))
    monkeypatch.setenv("HOME", str(home))
    scixplorer.data.clear()
    (cache / "uat.json").write_text(UAT_JSON, encoding="utf-8")
    (cache / "planetary_features.csv").write_text(PLANETARY_FEATURES_CSV, encoding="utf-8")
    monkeypatch.setattr(scixplorer.data, "refresh", functools.partial(scixplorer.data.refresh, transport=refresh_transport()))
    config = scixplorer.config
    saved = {field.name: getattr(config, field.name) for field in dataclasses.fields(config)}
    previous = scixplorer.client._default_client
    api = DocsAPI()
    scixplorer.set_default_client(api.client())
    try:
        yield api
    finally:
        scixplorer.set_default_client(previous)
        for name, value in saved.items():
            setattr(config, name, value)
        scixplorer.data.clear()


def run_page(page: Path, *, show: bool = False) -> tuple[int, int, int]:
    """Run a page's blocks in the current environment; return (executed, checks, skipped)."""
    namespace: dict[str, Any] = {"__name__": "__docs__"}
    executed = checks = skipped = 0
    for block in blocks(page):
        if block.directive == "skip":
            skipped += 1
            continue
        try:
            checks += run_block(block, namespace, show=show)
        except ExampleFailure as exc:
            raise ExampleFailure(f"{block.label}: {exc}\n--- block source ---\n{block.source}") from None
        executed += 1
    return executed, checks, skipped


@pytest.mark.parametrize("page", pages(), ids=_page_id)
def test_examples_run(page: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    with offline_environment(tmp_path, monkeypatch) as api:
        run_page(page)
        searches = [r for r in api.requests if r.headers.get("authorization") != "Bearer docs-example-token"]
        assert not searches, "a request was sent without the example client's token"


def _names_used(source: str, candidates: set[str]) -> set[str]:
    """The ``candidates`` that ``source`` reads as bare names."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return {name for name in candidates if re.search(rf"(?<![\w.]){re.escape(name)}\b", source)}
    return {node.id for node in ast.walk(tree) if isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load)} & candidates


@pytest.mark.parametrize("page", pages(), ids=_page_id)
def test_examples_import_only_the_names_they_use(page: Path) -> None:
    if DEVELOPER in page.parents:
        pytest.skip("developer pages may import internals")
    found = blocks(page)
    if not found:
        return
    first = found[0].source.lstrip("\n").splitlines()[0]
    assert _IMPORT_LINE.match(first), (
        f"{found[0].label}: the first Python block must start with 'from scixplorer import <names>', not {first!r}"
    )
    imported: set[str] = set()
    for block in found:
        for number, line in enumerate(block.source.splitlines(), start=block.line + 1):
            where = f"{_page_id(page)}:{number}"
            assert not _PLAIN_IMPORT.match(line), f"{where}: import the names you use, not {line.strip()!r}"
            match = _FROM_PACKAGE.match(line)
            if match is None:
                continue
            names = [name.strip() for name in match.group("names").strip("()").split(",")]
            assert "*" not in names, f"{where}: import the names the page uses, not '*'"
            assert names == sorted(set(names)), f"{where}: sort the imported names: {', '.join(sorted(set(names)))}"
            imported.update(names)
    source = "\n".join(block.source for block in found)
    public = set(scixplorer.__all__)
    used = _names_used(source, public | imported)
    assert not (used & public) - imported, f"{_page_id(page)}: uses {sorted((used & public) - imported)} without importing them"
    assert not imported - used, f"{_page_id(page)}: imports {sorted(imported - used)} but does not use them"


def test_directives_are_well_formed() -> None:
    """A misspelt directive would silently run (or not run) a block, so every one must parse."""
    for page in pages():
        for number, line in enumerate(page.read_text(encoding="utf-8").splitlines(), start=1):
            if line.lstrip().startswith("<!--") and "docs-test" in line:
                assert _DIRECTIVE.match(line), f"{_page_id(page)}:{number}: malformed directive {line.strip()!r}"


def test_the_harness_detects_failures(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """The checks themselves work: a wrong expectation, a missing exception and a stray warning fail."""
    page = tmp_path / "page.md"
    cases = {
        "```python\n1 + 1\n# -> 3\n```\n": "expected '3'",
        "<!-- docs-test: raises ValueError -->\n```python\nx = 1\n```\n": "was expected to raise",
        "```python\nimport warnings\nwarnings.warn('x')\n```\n": "emitted warnings",
        "```python\nraise KeyError('k')\n```\n": "raised KeyError",
    }
    with offline_environment(tmp_path, monkeypatch):
        for text, message in cases.items():
            page.write_text(text, encoding="utf-8")
            with pytest.raises(ExampleFailure, match=re.escape(message)):
                run_page(page)
        page.write_text("```python\nx = 2\nx * 3\n# -> 6\n```\n<!-- docs-test: skip -->\n```python\n1/0\n```\n", encoding="utf-8")
        assert run_page(page) == (1, 1, 1)

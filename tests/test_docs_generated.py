"""The generated reference pages of the documentation match the code."""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "gen_docs.py"
REFERENCE = ROOT / "docs" / "content" / "reference"
MARKER = "<!-- Generated by scripts/gen_docs.py"
GENERATED = [
    "document-fields.md",
    "models.md",
    "expressions.md",
    "api/_index.md",
    "api/models.md",
    "api/query.md",
    "api/client.md",
    "api/exceptions.md",
    "api/data.md",
    "api/services.md",
    "api/utils.md",
]


def test_generated_pages_are_up_to_date() -> None:
    result = subprocess.run(
        [sys.executable, str(SCRIPT), "--check"], cwd=ROOT, capture_output=True, text=True, timeout=120
    )
    assert result.returncode == 0, result.stderr + result.stdout


def test_generated_pages_start_with_front_matter_and_the_marker() -> None:
    for relative in GENERATED:
        text = (REFERENCE / relative).read_text(encoding="utf-8")
        assert text.startswith("---\ntitle: "), relative
        front, _, body = text[4:].partition("\n---\n")
        assert "weight: " in front and "description: " in front, relative
        assert body.lstrip().startswith(MARKER), relative


def test_cheat_sheet_has_enough_rows() -> None:
    text = (REFERENCE / "expressions.md").read_text(encoding="utf-8")
    rows = [line for line in text.splitlines() if line.startswith("| `scix.")]
    assert len(rows) >= 60


def test_generated_pages_describe_a_single_token() -> None:
    """The documentation describes one API token; the generator replaces docstrings that say otherwise."""
    pattern = re.compile(r"several tokens|iterable of tokens|another token|every token|next token|Iterable\[str\]", re.I)
    for relative in GENERATED:
        text = (REFERENCE / relative).read_text(encoding="utf-8")
        assert not pattern.search(text), relative


def test_generated_examples_import_the_package_as_scix() -> None:
    for relative in GENERATED:
        text = (REFERENCE / relative).read_text(encoding="utf-8")
        assert not re.search(r"^\s*from scixplorer\b|^\s*import scixplorer(?! as scix)", text, re.M), relative
